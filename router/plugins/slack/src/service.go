// ----- Type conversion helpers -----
//
// These translate between the domain types from the slackclient package and
// the protobuf types generated by wgc. Optional (nullable) GraphQL fields
// map to protobuf wrapper types: an empty domain value becomes a nil wrapper
// so the router renders the field as null instead of an empty string.

func strPtr(v string) *wrapperspb.StringValue {
	if v == "" {
		return nil
	}
	return wrapperspb.String(v)
}

func int32Ptr(v int) *wrapperspb.Int32Value {
	if v == 0 {
		return nil
	}
	return wrapperspb.Int32(int32(v))
}

func toProtoChannel(c *slackclient.Channel) *service.SlackChannel {
	return &service.SlackChannel{
		Id:          c.ID,
		Name:        c.Name,
		Topic:       strPtr(c.Topic),
		Purpose:     strPtr(c.Purpose),
		MemberCount: int32Ptr(c.MemberCount),
		IsPrivate:   c.IsPrivate,
	}
}

func toProtoMessage(m slackclient.Message) *service.SlackMessage {
	return &service.SlackMessage{
		ChannelId: m.ChannelID,
		Ts:        m.TS,
		UserId:    m.UserID,
		Text:      m.Text,
		ThreadTs:  strPtr(m.ThreadTS),
		Permalink: strPtr(m.Permalink),
	}
}

func toProtoMessages(msgs []slackclient.Message) []*service.SlackMessage {
	out := make([]*service.SlackMessage, 0, len(msgs))
	for _, m := range msgs {
		out = append(out, toProtoMessage(m))
	}
	return out
}

func toProtoUser(u *slackclient.User) *service.SlackUser {
	return &service.SlackUser{
		Id:       u.ID,
		Name:     u.Name,
		RealName: strPtr(u.RealName),
		Email:    strPtr(u.Email),
		IsBot:    u.IsBot,
	}
}
