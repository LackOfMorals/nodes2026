// Service implementation for the Slack Cosmo Connect plugin.
//
// SlackService maps the gRPC contract generated from src/schema.graphql
// (by `wgc router plugin generate`) onto the Slack Web API via the
// slackclient.Client interface.
//
// Conventions:
//   - "not found" (channel/user the bot cannot see) maps to a nil result,
//     not an error — that is the GraphQL convention for nullable queries.
//   - List queries return an empty list on not-found.
//   - Any other Slack/API error is returned as a gRPC error.
//   - Optional scalar arguments arrive as protobuf wrappers
//     (google.protobuf.Int32Value / StringValue); nil means "absent" and
//     the schema default applies.
package main

import (
	"context"
	"errors"
	"fmt"

	service "github.com/wundergraph/cosmo/plugin/generated"
	slackclient "github.com/wundergraph/cosmo/plugin/src/slackclient"
	"google.golang.org/protobuf/types/known/wrapperspb"
)

// SlackService implements the generated gRPC server interface.
type SlackService struct {
	service.UnimplementedSlackServiceServer

	slack slackclient.Client
}

// NewSlackService builds a SlackService backed by the given Slack client.
func NewSlackService(c slackclient.Client) *SlackService {
	return &SlackService{slack: c}
}

// QuerySlackChannel implements the slackChannel(id: ID!) GraphQL query.
func (s *SlackService) QuerySlackChannel(
	ctx context.Context,
	req *service.QuerySlackChannelRequest,
) (*service.QuerySlackChannelResponse, error) {
	ch, err := s.slack.GetChannel(ctx, req.GetId())
	if err != nil {
		if errors.Is(err, slackclient.ErrNotFound) {
			return &service.QuerySlackChannelResponse{}, nil
		}
		return nil, fmt.Errorf("slackChannel: %w", err)
	}

	return &service.QuerySlackChannelResponse{
		SlackChannel: toProtoChannel(ch),
	}, nil
}

// QuerySlackMessages implements slackMessages(channelId: ID!, limit: Int = 50).
func (s *SlackService) QuerySlackMessages(
	ctx context.Context,
	req *service.QuerySlackMessagesRequest,
) (*service.QuerySlackMessagesResponse, error) {
	limit := 50
	if l := req.GetLimit(); l != nil {
		limit = int(l.GetValue())
	}

	msgs, err := s.slack.GetMessages(ctx, req.GetChannelId(), limit)
	if err != nil {
		if errors.Is(err, slackclient.ErrNotFound) {
			return &service.QuerySlackMessagesResponse{SlackMessages: nil}, nil
		}
		return nil, fmt.Errorf("slackMessages: %w", err)
	}

	return &service.QuerySlackMessagesResponse{
		SlackMessages: toProtoMessages(msgs),
	}, nil
}

